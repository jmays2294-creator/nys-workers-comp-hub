// Build-time only, kept outside the plugin. Imports make-colors.js from the skill folder (never copied
// into the plugin) and writes the finished ThemeColors object into the plugin as plain data.
// Usage: node build-suite-theme.mjs <path to make-colors.js> <output .ts file> [navy|desk]
import { writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const [, , makeColorsPath, outPath, variant = 'navy'] = process.argv
const { makeColors, checkColors } = await import(pathToFileURL(makeColorsPath).href)
const build = (makeColorsPath.match(/bundled-skills\/([0-9.]+)\//) ?? [])[1] ?? 'unknown'

const ROLES = {
  // navy: the app kit's action colour as accent; the brand orange ink kept small, in `pro` (code literals).
  navy: { accent: '#1B2A4A', danger: '#B42318', success: '#1F6B47', warning: '#8A5200', pro: '#A64B0D' },
  // desk: the website desk's action orange as accent, its state colours as roles.
  desk: { accent: '#B0560A', danger: '#A23B2A', success: '#2B6A48', warning: '#7C5E0C', pro: '#2F5F92' },
}
const roles = ROLES[variant]
if (roles === undefined) { console.error(`unknown variant ${variant}`); process.exit(2) }

const { theme, problems } = makeColors({
  label: 'The Comp Desk Paper', id: 'tcd-paper',
  roles,
  light: { gray: { anchors: {
    'surface-0': '#F4EFE6', 'surface-1': '#FBF8F2', 'surface-2': '#FFFEFB', 'surface-3': '#FFFEFB',
    'text-primary': '#1B2A4A', 'text-secondary': '#46516A', 'text-muted': '#5E6474' } } },
  dark: { gray: { anchors: {
    'surface-0': '#10151F', 'surface-1': '#141B28', 'surface-2': '#182030', 'surface-3': '#1C2537',
    'text-primary': '#ECE6DA', 'text-secondary': '#C3BDB1', 'text-muted': '#A29D93' } } },
})
const refused = [...problems, ...checkColors(theme)].filter(line => line.startsWith("Desktop won't paint"))
if (refused.length > 0) { console.error(refused.join('\n')); process.exit(1) }

const body = `// Generated by build-suite-theme.mjs from the design system's make-colors.js (Claude Code ${build}).
// Inputs: app kit paper / night paper grays; roles ${JSON.stringify(roles)}.
// Plain data. Do not edit by hand; rerun the build when Claude Code updates.
import type { ThemeColors } from 'claude-code'

export const COLORS: ThemeColors = ${JSON.stringify(theme, null, 2)}
`
writeFileSync(outPath, body)
console.log(`wrote ${outPath}: ${body.length} chars, ${problems.length} advisory lines, build ${build}`)
for (const line of problems) console.log('  advisory: ' + line)
